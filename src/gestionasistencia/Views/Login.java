    private void iniciarSesion() {
        String correo = txt_correo.getText().trim();
        String contrasena = new String(txt_contrasena.getPassword());

        if (correo.isEmpty() || contrasena.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Debe ingresar el correo y la contraseña.");
            return;
        }

        ResultadoAutenticacion resultado
                = controlador.autenticarUsuario(correo, contrasena);

        if (!resultado.isExitoso()) {
            JOptionPane.showMessageDialog(this, resultado.getMensaje());
            txt_contrasena.setText("");
            return;
        }

        Usuario usuario = resultado.getUsuario();
        SesionUsuario.iniciarSesion(usuario);
        dispose();

        if ("Administrador".equalsIgnoreCase(usuario.getRol().trim())) {
            new GestionUsuario().setVisible(true);
        } else {
            new ControlAsistencia(usuario).setVisible(true);
        }
    }

