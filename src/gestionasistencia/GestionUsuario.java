    private void tbl_usuarioMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tbl_usuarioMouseClicked
        int fila =
                tbl_usuario.getSelectedRow();


        if (fila >= 0) {

            int id =
                    Integer.parseInt(
                            tbl_usuario
                                    .getValueAt(fila, 0)
                                    .toString()
                    );


            Usuario usuario =
                    controlador.buscarUsuario(id);


            if (usuario != null) {

                txt_id.setText(
                        String.valueOf(
                                usuario.getId()
                        )
                );

                txt_nombre.setText(
                        usuario.getNombre()
                );

                txt_correo.setText(
                        usuario.getCorreo()
                );

                txt_contrasena.setText(
                        usuario.getContrasena()
                );

                cmb_rol.setSelectedItem(
                        usuario.getRol()
                );
            }
        }
    }//GEN-LAST:event_tbl_usuarioMouseClicked

