    private void btn_buscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_buscarActionPerformed
        if (txt_id.getText().trim().isEmpty()) {

            JOptionPane.showMessageDialog(
                    this,
                    "Ingrese un ID"
            );

            return;
        }

        try {

            int id = Integer.parseInt(
                    txt_id.getText().trim()
            );

            Usuario usuario =
                    controlador.buscarUsuario(id);

            if (usuario != null) {

                txt_nombre.setText(
                        usuario.getNombre()
                );

                txt_correo.setText(
                        usuario.getCorreo()
                );

                txt_contrasena.setText(
                        usuario.getContrasena()
                );

                cmb_rol.setSelectedItem(
                        usuario.getRol()
                );

            } else {

                JOptionPane.showMessageDialog(
                        this,
                        "Usuario no encontrado"
                );

                limpiarCampos();
            }

        } catch (NumberFormatException e) {

            JOptionPane.showMessageDialog(
                    this,
                    "El ID debe ser un número"
            );
        }
        
    }//GEN-LAST:event_btn_buscarActionPerformed

    private void btn_crearActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_crearActionPerformed
        if (!validarCampos()) {
        return;
        }

        String nombre = txt_nombre.getText().trim();
        String correo = txt_correo.getText().trim();
        String contrasena = txt_contrasena.getText();
        String rol = cmb_rol.getSelectedItem().toString();


        // VALIDAR SI EL CORREO YA EXISTE
        if (controlador.existeCorreo(correo)) {

            JOptionPane.showMessageDialog(
                    this,
                    "Ya existe un usuario registrado con ese correo"
            );

            return;
        }


        Usuario usuario = new Usuario(
                0,
                nombre,
                correo,
                contrasena,
                rol
        );


        boolean resultado =
                controlador.crearUsuario(usuario);


        if (resultado) {

            JOptionPane.showMessageDialog(
                    this,
                    "Usuario creado correctamente"
            );

            limpiarCampos();
            cargarTablaUsuarios();

        } else {

            JOptionPane.showMessageDialog(
                    this,
                    "No se pudo crear el usuario"
            );
        }
    }//GEN-LAST:event_btn_crearActionPerformed

