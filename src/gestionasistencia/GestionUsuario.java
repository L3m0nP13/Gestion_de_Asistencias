    private void cargarTablaUsuarios() {

        DefaultTableModel modelo =
                (DefaultTableModel) tbl_usuario.getModel();

        modelo.setRowCount(0);

        for (Usuario usuario : controlador.listarUsuarios()) {

            Object[] fila = {

                usuario.getId(),
                usuario.getNombre(),
                usuario.getCorreo(),
                usuario.getRol()

            };

            modelo.addRow(fila);
        }
    }
    
    private void limpiarCampos() {

        txt_id.setText("");
        txt_nombre.setText("");
        txt_contrasena.setText("");
        txt_correo.setText("");

        cmb_rol.setSelectedIndex(-1);

        tbl_usuario.clearSelection();

        txt_id.requestFocus();
    }
    
    private boolean validarCampos() {

        if (txt_nombre.getText().trim().isEmpty()) {

            JOptionPane.showMessageDialog(
                    this,
                    "Debe ingresar el nombre"
            );

            return false;
        }

        if (txt_correo.getText().trim().isEmpty()) {

            JOptionPane.showMessageDialog(
                    this,
                    "Debe ingresar el correo"
            );

            return false;
        }

        if (txt_contrasena.getText().trim().isEmpty()) {

            JOptionPane.showMessageDialog(
                    this,
                    "Debe ingresar la contraseña"
            );

            return false;
        }

        if (cmb_rol.getSelectedIndex() == -1) {

            JOptionPane.showMessageDialog(
                    this,
                    "Debe seleccionar un rol"
            );

            return false;
        }

        return true;
    }
    
    
    
    
    
    
    
